String chineseUi(String value) {
  final exact = zh[value];
  if (exact != null) return exact;
  for (final template in _templates) {
    final match = template.pattern.firstMatch(value);
    if (match == null) continue;
    var index = 0;
    return template.translation.replaceAllMapped(
      RegExp(r'\{value\}'),
      (_) => match.group(++index)!,
    );
  }
  return value.replaceAllMapped(
    RegExp(
      r'\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\d{1,2}), (\d{4})\b',
    ),
    (match) {
      final month =
          const [
            'Jan',
            'Feb',
            'Mar',
            'Apr',
            'May',
            'Jun',
            'Jul',
            'Aug',
            'Sep',
            'Oct',
            'Nov',
            'Dec',
          ].indexOf(match[1]!) +
          1;
      return '${match[3]}年$month月${match[2]}日';
    },
  );
}

